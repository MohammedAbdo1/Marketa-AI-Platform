// Update document head
const updateHead = () => {
  // Update title
  document.title = `${props.title} - نظام الحملات التسويقية`
  
  // Update meta description
  updateMetaTag('description', props.description)
  updateMetaTag('keywords', props.keywords)
  
  // Update language
  document.documentElement.lang = props.locale
  document.documentElement.dir = props.locale === 'ar' ? 'rtl' : 'ltr'
  
  // Update Open Graph tags
  updateMetaTag('og:title', props.title, 'property')
  updateMetaTag('og:description', props.description, 'property')
  updateMetaTag('og:locale', props.locale === 'ar' ? 'ar_SA' : 'en_US', 'property')
}

const updateMetaTag = (name, content, attribute = 'name') => {
  let meta = document.querySelector(`meta[${attribute}="${name}"]`)
  if (!meta) {
    meta = document.createElement('meta')
    meta.setAttribute(attribute, name)
    document.head.appendChild(meta)
  }
  meta.setAttribute('content', content)
}

// Watch for prop changes
watch(() => [props.title, props.description, props.keywords, props.locale], updateHead, { immediate: true })

onMounted(() => {
  updateHead()
